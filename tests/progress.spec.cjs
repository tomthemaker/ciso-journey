const { test, expect } = require('@playwright/test');
test('progress route is readable, keyboard navigable, and does not change learning state', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('./#progress');
  await expect(page.locator('body')).toHaveAttribute('data-storage-busy', 'false');
  await expect(page.getByRole('heading', { name: 'Progress', exact: true })).toBeVisible();
  await expect(page.locator('#progressReport')).toContainText('No review self-ratings');
  await expect(page.locator('#progressReport')).toContainText('Historical trends are unavailable');
  await page.evaluate(() => { document.body.style.zoom = '200%'; });
  await expect(page.locator('#progressReport')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBeTruthy();
  await page.getByRole('button', { name: 'Roadmap', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/#roadmap/);
  await page.getByRole('button', { name: 'Progress', exact: true }).click();
  await expect(page.locator('#progressReport')).toContainText('No keyed MCQ attempts');
});
test('committed practice appears separately without changing the saved snapshot', async ({ page }) => {
  const { studyBundle: bundle } = require('../scripts/study-content.cjs');
  const question = bundle.records.find(r => r.kind === 'question' && r.payload.format === 'mcq');
  await page.goto(`./#questions/${question.id}/${question.version}`);
  await expect(page.locator('body')).toHaveAttribute('data-storage-busy', 'false');
  await page.locator('#answer-' + question.payload.correctOptionId).check();
  await page.locator('#submitAttempt').click();
  await expect(page.locator('.attempt-result')).toHaveCount(1);
  const snapshot = () => page.evaluate(() => new Promise(resolve => { const request = indexedDB.open('ciso-journey', 1); request.onsuccess = () => { const db = request.result, tx = db.transaction('snapshots'), get = tx.objectStore('snapshots').get('current'); tx.oncomplete = () => { db.close(); resolve(get.result); }; }; }));
  const before = await snapshot();
  await page.getByRole('button', { name: 'Progress', exact: true }).click();
  await expect(page.locator('#progressReport')).toContainText('1 correct of 1 keyed MCQ attempts');
  await expect(page.locator('#progressReport')).toContainText('No review self-ratings');
  expect(await snapshot()).toEqual(before);
});
test('case self-assessment is shown by exact rubric and dated criterion', async ({ page }) => {
  const { studyBundle: bundle } = require('../scripts/study-content.cjs');
  const scenario = bundle.records.filter(r => r.kind === 'scenario' && r.id === 'scenario-foundation-decision').sort((a, b) => b.version - a.version)[0];
  await page.goto(`./#cases/${scenario.id}/${scenario.version}`);
  await expect(page.locator('body')).toHaveAttribute('data-storage-busy', 'false');
  for (const key of ['impact', 'options', 'accountableOwner', 'recommendation', 'residualRisk']) await page.locator('#case-' + key).fill('Synthetic practice');
  await page.getByLabel('Evidence title', { exact: true }).fill('Synthetic evidence');
  await page.locator('#saveCaseResponse').click();
  const form = page.getByRole('form', { name: 'Self-assess case response 1' });
  for (const select of await form.locator('select').all()) await select.selectOption('1');
  await form.getByRole('button', { name: 'Save case self-assessment' }).click();
  await expect(form).toHaveCount(0);
  await page.getByRole('button', { name: 'Progress', exact: true }).click();
  await expect(page.locator('#progressReport')).toContainText('1 self-assessments');
  await expect(page.locator('#progressReport')).toContainText(`${scenario.payload.rubricRef.id}@${scenario.payload.rubricRef.version}`);
  await expect(page.locator('.progress-rubric li').first()).toContainText(/\d{4}-\d{2}-\d{2} — 1:/);
});
test('quarterly self-report history and portfolio references are read-only in Progress', async ({ page }) => {
  await page.goto('./#competencies');
  await expect(page.locator('body')).toHaveAttribute('data-storage-busy', 'false');
  await page.locator('#portfolio-title').fill('Synthetic evidence');
  await page.getByRole('button', { name: 'Save evidence' }).click();
  for (const [date, level] of [['2026-03-31', 'Recognize'], ['2026-04-01', 'Apply']]) {
    await page.locator('#appraisal-date').fill(date);
    await page.locator('#appraisal-competency').selectOption('Governance');
    await page.locator('#appraisal-level').selectOption(level);
    await page.locator('#appraisal-scope').fill('Synthetic pilot');
    await page.locator('#appraisal-rationale').fill('Bounded self-report');
    await page.locator('#appraisal-evidenceId').selectOption({ label: 'Synthetic evidence' });
    await page.getByRole('button', { name: 'Save self-assessment' }).click();
    await expect(page.locator('#appraisalHistory')).toBeFocused();
  }
  const snapshot = () => page.evaluate(() => new Promise(resolve => { const request = indexedDB.open('ciso-journey', 1); request.onsuccess = () => { const db = request.result, tx = db.transaction('snapshots'), get = tx.objectStore('snapshots').get('current'); tx.oncomplete = () => { db.close(); resolve(get.result); }; }; }));
  const before = await snapshot();
  await page.getByRole('button', { name: 'Progress', exact: true }).click();
  const report = page.locator('#progressReport');
  await expect(report).toContainText('2026 Q1 · 2026-03-31 · Recognize · self-assessment');
  await expect(report).toContainText('2026 Q2 · 2026-04-01 · Apply · self-assessment');
  await expect(report).toContainText('Prior self-report for this exact scope and provenance: 2026-03-31 · Recognize');
  await expect(report).toContainText('Portfolio evidence');
  await page.getByLabel('Event window').selectOption('90');
  await expect(page.getByLabel('Event window')).toBeFocused();
  await expect(report).toContainText('2026 Q2 · 2026-04-01 · Apply · self-assessment');
  expect(await snapshot()).toEqual(before);
  await page.reload();
  await expect(report).toContainText('2026 Q2 · 2026-04-01 · Apply · self-assessment');
  expect(await snapshot()).toEqual(before);
});
